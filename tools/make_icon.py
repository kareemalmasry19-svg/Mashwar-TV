"""Builds the 'المصري TV' gold-calligraphy launcher icon as an Android VectorDrawable + SVG preview."""
import sys, uharfbuzz as hb
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen

def shape(fontfile, text, direction):
    data = open(fontfile, "rb").read()
    face = hb.Face(data); font = hb.Font(face)
    buf = hb.Buffer(); buf.add_str(text); buf.guess_segment_properties()
    buf.direction = direction
    hb.shape(font, buf, {"liga": True, "calt": True, "dlig": True})
    tt = TTFont(fontfile); gs = tt.getGlyphSet(); order = tt.getGlyphOrder()
    return [(order[i.codepoint], p.x_advance, p.x_offset, p.y_offset) for i, p in zip(buf.glyph_infos, buf.glyph_positions)], gs

def outline(fontfile, text, direction, box):
    """SVG path of the shaped text, scaled to fit box=(cx, cy, maxw, maxh) in icon coords (y down)."""
    glyphs, gs = shape(fontfile, text, direction)
    # bounds in font units
    bp = BoundsPen(gs); x = 0
    for name, adv, dx, dy in glyphs:
        gs[name].draw(TransformPen(bp, (1, 0, 0, 1, x + dx, dy))); x += adv
    x0, y0, x1, y1 = bp.bounds
    cx, cy, mw, mh = box
    s = min(mw / (x1 - x0), mh / (y1 - y0))
    sp = SVGPathPen(gs, ntos=lambda v: ("%.2f" % v).rstrip("0").rstrip("."))
    x = 0
    for name, adv, dx, dy in glyphs:
        # font units (y up) → icon units (y down), centred in the box
        t = (s, 0, 0, -s, cx - (x0 + x1) / 2 * s + (x + dx) * s, cy + (y0 + y1) / 2 * s - dy * s)
        gs[name].draw(TransformPen(sp, t)); x += adv
    return sp.getCommands()

