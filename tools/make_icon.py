def star(x, y, r):  # 4-point glint
    return f"M{x},{y-r*3}L{x+r*0.5},{y-r*0.5}L{x+r*3},{y}L{x+r*0.5},{y+r*0.5}L{x},{y+r*3}L{x-r*0.5},{y+r*0.5}L{x-r*3},{y}L{x-r*0.5},{y-r*0.5}Z"

